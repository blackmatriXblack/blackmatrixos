    out dx,al
    mov dx,0x3D4
    mov ax,0x0E11
    out dx,ax
    mov ax,0x0D06
    out dx,ax
    mov ax,0x3E07
    out dx,ax
    mov ax,0x4109
    out dx,ax
    mov ax,0xEA10
    out dx,ax
    mov ax,0x2C11
    out dx,ax
    mov ax,0xDF12
    out dx,ax
    mov ax,0x0014
    out dx,ax
    mov ax,0xE715
    out dx,ax
    mov ax,0x0616
    out dx,ax
    mov ax,0xE317
