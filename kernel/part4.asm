gui_mode:
    call set_mode13h
    mov edi,GFX
    mov ecx,320*200
    mov al,1
    rep stosb
    mov edi,GFX+320*180
    mov ecx,320*20
    mov al,8
    rep stosb
    mov edi,GFX+320*182+4
    mov ecx,16
.sb:push ecx
    mov ecx,50
.s2:mov byte [edi],2
    inc edi
    dec ecx
    jnz .s2
    add edi,320-50
    pop ecx
    dec ecx
    jnz .sb
    mov edi,GFX+320*20+20
    mov ecx,140
.w1:push ecx
    mov ecx,200
.w2:mov byte [edi],7
    inc edi
    dec ecx
    jnz .w2
    add edi,320-200
    pop ecx
    dec ecx
    jnz .w1
    mov edi,GFX+320*20+20
    mov ecx,14
.t1:push ecx
    mov ecx,200
.t2:mov byte [edi],9
    inc edi
    dec ecx
    jnz .t2
    add edi,320-200
    pop ecx
    dec ecx
    jnz .t1
    mov edi,GFX+320*50+140
    mov ecx,100
.w3:push ecx
    mov ecx,150
.w4:mov byte [edi],15
    inc edi
    dec ecx
    jnz .w4
    add edi,320-150
    pop ecx
    dec ecx
    jnz .w3
    mov edi,GFX+320*50+140
    mov ecx,14
.t3:push ecx
    mov ecx,150
.t4:mov byte [edi],1
    inc edi
    dec ecx
    jnz .t4
    add edi,320-150
    pop ecx
    dec ecx
    jnz .t3
.gl:in al,0x64
    test al,1
    jz .gl
    in al,0x60
    test al,0x80
    jnz .gl
    cmp al,0x01
    jne .gl
    call set_textmode
    call cls
    ret
